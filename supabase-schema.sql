-- 1. Create the checklist_items table
CREATE TABLE IF NOT EXISTS public.checklist_items (
    id TEXT PRIMARY KEY,
    checked BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Enable Row Level Security (RLS)
ALTER TABLE public.checklist_items ENABLE ROW LEVEL SECURITY;

-- 3. Configure Policies for Public Collaborative Access
-- Note: As this checklist is public without login, anyone with the project URL and anon key can read and update.
-- See README.md for recommendations on authentication and rate limiting for abuse prevention.

-- Allow public read access
DROP POLICY IF EXISTS "Allow public read checklist items" ON public.checklist_items;
CREATE POLICY "Allow public read checklist items"
    ON public.checklist_items
    FOR SELECT
    TO public, anon, authenticated
    USING (true);

-- Allow public update access (checkbox toggle)
DROP POLICY IF EXISTS "Allow public update checklist items" ON public.checklist_items;
CREATE POLICY "Allow public update checklist items"
    ON public.checklist_items
    FOR UPDATE
    TO public, anon, authenticated
    USING (true)
    WITH CHECK (true);

-- Allow public insert access (required for upsert / initial setup)
DROP POLICY IF EXISTS "Allow public insert checklist items" ON public.checklist_items;
CREATE POLICY "Allow public insert checklist items"
    ON public.checklist_items
    FOR INSERT
    TO public, anon, authenticated
    WITH CHECK (true);

-- 4. Enable Supabase Realtime
-- This broadcasts INSERT and UPDATE events to connected browser sessions
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables 
        WHERE pubname = 'supabase_realtime' 
          AND schemaname = 'public' 
          AND tablename = 'checklist_items'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.checklist_items;
    END IF;
END $$;

ALTER TABLE public.checklist_items REPLICA IDENTITY FULL;

